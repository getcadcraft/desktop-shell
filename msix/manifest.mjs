// msix/manifest.mjs — AppxManifest.xml for CadCraft Studio as an MSIX package (0.7 MSIX; the spike is
// stores/msstore/MSIX-SPIKE.md in the site's checkout). Pure: data in, XML text out, so the tests need no Windows.
//
// What the NSIS hooks (build.mjs `hooks()`) do at install time is declared here instead, because an MSIX can't run scripts:
//   file types   → uap:FileTypeAssociation, one per extension. Windows never gives a package a default silently: the person
//                  picks Studio once in "Open with" — the same as our "polite" rule; "own types by default" does not exist here.
//   ccstudio://  → uap:Protocol
//   Live         → desktop2:FirewallRules (inbound, this program, private networks)
//   Start tiles  → one <Application> per app with uap10:Parameters="--app=<slug>" (Windows 10 2004+), each its own tile
//   full trust   → rescap:runFullTrust (a Tauri shell is a normal Win32 program)
// The identity (Name, Publisher) is what Partner Center reserved: the owner's, passed in, never invented here.

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

/** x.y.z → x.y.z.0 (the Store takes the last part as 0 and wants every submission higher than the one before). */
export function msixVersion(v) {
  const m = /^(\d+)\.(\d+)(?:\.(\d+))?(?:\.0)?$/.exec(String(v));
  if (!m) throw new Error(`the MSIX version must be x.y or x.y.z, not "${v}"`);
  return `${m[1]}.${m[2]}.${m[3] || 0}.0`;
}

/** A FileTypeAssociation Name: lower case letters and digits only (the schema allows nothing else), unique per extension. */
export const ftaName = (ext) => 'cc' + String(ext).toLowerCase().replace(/[^a-z0-9]/g, '');

/** The Application Id: letters and digits, starts with a letter (the schema's rule). */
export const appId = (slug) => slug.replace(/[^A-Za-z0-9]/g, '').replace(/^(\d)/, 'A$1');

/**
 * @param {object} o
 * @param {string} o.identityName    Partner Center's package identity name, e.g. TheDataDesignGroup.CadCraftStudio
 * @param {string} o.publisher       its publisher, "CN=…" exactly as Partner Center shows it
 * @param {string} o.publisherDisplay the name people see
 * @param {string} o.version         x.y.z
 * @param {string} o.displayName     "CadCraft Studio"
 * @param {string} o.description
 * @param {string} o.exe             the program inside the package, e.g. "CadCraft Studio.exe"
 * @param {{slug:string,name:string,role?:string}[]} o.apps  the eight apps (a tile each)
 * @param {{ext:string,label:string}[]} o.fileTypes  every extension Studio opens
 * @param {string} [o.language]      default en-us
 */
export function manifest(o) {
  for (const k of ['identityName', 'publisher', 'publisherDisplay', 'version', 'displayName', 'exe']) if (!o[k]) throw new Error(`manifest: ${k} is required`);
  if (!/^[A-Za-z0-9][A-Za-z0-9.\-]{2,49}$/.test(o.identityName)) throw new Error(`manifest: identity name "${o.identityName}" is not a valid package name (3–50 letters, digits, . and -)`);
  if (!/^CN=/.test(o.publisher)) throw new Error('manifest: the publisher must be the "CN=…" string Partner Center gives');
  const apps = o.apps || [];
  const seen = new Set();
  for (const a of apps) { const id = appId(a.slug); if (seen.has(id) || id === 'Studio') throw new Error(`manifest: app id ${id} clashes`); seen.add(id); }
  const exts = [...new Map((o.fileTypes || []).map((f) => [String(f.ext).toLowerCase(), f])).values()];
  const L = [];
  const w = (n, s) => L.push('  '.repeat(n) + s);

  L.push('<?xml version="1.0" encoding="utf-8"?>');
  L.push('<!-- Generated by desktop-shell/msix/manifest.mjs. Do not edit: change the generator. -->');
  L.push('<Package xmlns="http://schemas.microsoft.com/appx/manifest/foundation/windows10"');
  L.push('         xmlns:uap="http://schemas.microsoft.com/appx/manifest/uap/windows10"');
  L.push('         xmlns:uap10="http://schemas.microsoft.com/appx/manifest/uap/windows10/10"');
  L.push('         xmlns:desktop2="http://schemas.microsoft.com/appx/manifest/desktop/windows10/2"');
  L.push('         xmlns:rescap="http://schemas.microsoft.com/appx/manifest/foundation/windows10/restrictedcapabilities"');
  L.push('         IgnorableNamespaces="uap uap10 desktop2 rescap">');
  w(1, `<Identity Name="${esc(o.identityName)}" Publisher="${esc(o.publisher)}" Version="${msixVersion(o.version)}" ProcessorArchitecture="x64" />`);
  w(1, '<Properties>');
  w(2, `<DisplayName>${esc(o.displayName)}</DisplayName>`);
  w(2, `<PublisherDisplayName>${esc(o.publisherDisplay)}</PublisherDisplayName>`);
  w(2, '<Logo>Assets\\StoreLogo.png</Logo>');
  w(1, '</Properties>');
  w(1, '<Dependencies>');
  // 10.0.19041.0 = Windows 10 2004, the first release that reads uap10:Parameters (a tile per app).
  w(2, '<TargetDeviceFamily Name="Windows.Desktop" MinVersion="10.0.19041.0" MaxVersionTested="10.0.26100.0" />');
  w(1, '</Dependencies>');
  w(1, `<Resources><Resource Language="${esc(o.language || 'en-us')}" /></Resources>`);
  w(1, '<Applications>');
  // The hub: Studio itself, with the file types and the link.
  w(2, `<Application Id="Studio" Executable="${esc(o.exe)}" uap10:RuntimeBehavior="packagedClassicApp" uap10:TrustLevel="mediumIL">`);
  w(3, `<uap:VisualElements DisplayName="${esc(o.displayName)}" Description="${esc(o.description || o.displayName)}" BackgroundColor="transparent" Square150x150Logo="Assets\\Studio-150.png" Square44x44Logo="Assets\\Studio-44.png">`);
  w(4, '<uap:DefaultTile Wide310x150Logo="Assets\\Studio-wide.png" />');
  w(3, '</uap:VisualElements>');
  w(3, '<Extensions>');
  if (exts.length) {
    for (const f of exts) {
      w(4, '<uap:Extension Category="windows.fileTypeAssociation">');
      w(5, `<uap:FileTypeAssociation Name="${ftaName(f.ext)}">`);
      w(6, `<uap:DisplayName>${esc(f.label || f.ext.toUpperCase() + ' file')}</uap:DisplayName>`);
      w(6, '<uap:SupportedFileTypes>');
      w(7, `<uap:FileType>.${esc(String(f.ext).toLowerCase())}</uap:FileType>`);
      w(6, '</uap:SupportedFileTypes>');
      w(5, '</uap:FileTypeAssociation>');
      w(4, '</uap:Extension>');
    }
  }
  w(4, '<uap:Extension Category="windows.protocol">');
  w(5, '<uap:Protocol Name="ccstudio">');
  w(6, `<uap:DisplayName>${esc(o.displayName)} link</uap:DisplayName>`);
  w(5, '</uap:Protocol>');
  w(4, '</uap:Extension>');
  w(3, '</Extensions>');
  w(2, '</Application>');
  // One tile per app: the same program, started into that app.
  for (const a of apps) {
    const id = appId(a.slug);
    w(2, `<Application Id="${id}" Executable="${esc(o.exe)}" uap10:Parameters="--app=${esc(a.slug)}" uap10:RuntimeBehavior="packagedClassicApp" uap10:TrustLevel="mediumIL">`);
    w(3, `<uap:VisualElements DisplayName="${esc(a.name)}" Description="${esc(a.role || a.name)}, in ${esc(o.displayName)}" BackgroundColor="transparent" Square150x150Logo="Assets\\${id}-150.png" Square44x44Logo="Assets\\${id}-44.png" />`);
    w(2, '</Application>');
  }
  w(1, '</Applications>');
  w(1, '<Capabilities>');
  w(2, '<Capability Name="internetClient" />');                // What's new, sign-in, the Live relay
  w(2, '<Capability Name="privateNetworkClientServer" />');    // Studio Live on the same network
  w(2, '<rescap:Capability Name="runFullTrust" />');
  w(1, '</Capabilities>');
  // Studio Live hosts on private networks only, for this program only (no fixed port: the session server binds a free one).
  // A package-level extension: Windows refuses windows.firewallRules under an Application ("should be declared under
  // <Package> extensions"; found installing on workstation11a, 2026-10-24).
  w(1, '<Extensions>');
  w(2, '<desktop2:Extension Category="windows.firewallRules">');
  w(3, `<desktop2:FirewallRules Executable="${esc(o.exe)}">`);
  w(4, '<desktop2:Rule Direction="in" IPProtocol="TCP" Profile="private" />');
  w(4, '<desktop2:Rule Direction="in" IPProtocol="UDP" Profile="private" />');
  w(3, '</desktop2:FirewallRules>');
  w(2, '</desktop2:Extension>');
  w(1, '</Extensions>');
  L.push('</Package>');
  return L.join('\n') + '\n';
}

/** The tile files the manifest names, as [file, size [w, h], app slug | null for Studio]. */
export function tiles(apps) {
  const out = [['StoreLogo.png', [50, 50], null], ['Studio-44.png', [44, 44], null], ['Studio-150.png', [150, 150], null], ['Studio-wide.png', [310, 150], null]];
  for (const a of apps) { const id = appId(a.slug); out.push([`${id}-44.png`, [44, 44], a.slug], [`${id}-150.png`, [150, 150], a.slug]); }
  return out;
}
